/**
 * Write a TypeORM migration from an answered plan: up() is Apso's change DDL,
 * down() the reverse, and the plan is saved beside the migration so the
 * answers that produced it stay with it.
 */
import * as fs from "fs";
import * as path from "path";
import { ApsorcType } from "../apsorc-parser";
import { openQuestions, Plan, planMigration, Question } from "../plan";
import { pascalCase } from "../utils/casing";
import { reviewMigration, Finding } from "../verify/review";
import { changeDdl, DownDdl, downDdl } from "./change";

const template = (sql: string) =>
  "`" +
  sql.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\${/g, "\\${") +
  "`";
const queries = (statements: string[]) =>
  statements
    .map((s) => `        await queryRunner.query(${template(s)});`)
    .join("\n");

export function typeormMigration(
  className: string,
  up: string[],
  down: DownDdl
): string {
  const downBody =
    "down" in down
      ? queries(down.down)
      : `        throw new Error(${JSON.stringify(
          `This migration can't be reversed automatically: ${down.irreversible.join(
            "; "
          )}`
        )});`;
  return `import { MigrationInterface, QueryRunner } from "typeorm";

// Generated by apso migrate generate from the answered migration plan saved beside this file.
export class ${className} implements MigrationInterface {
    name = '${className}'

    public async up(queryRunner: QueryRunner): Promise<void> {
${queries(up)}
    }

    public async down(queryRunner: QueryRunner): Promise<void> {
${downBody}
    }

}
`;
}

export interface PlannedMigration {
  ok: boolean;
  needed: boolean;
  /** Questions still open in the plan; nothing is written while any are. */
  open?: Question[];
  file?: string;
  planFile?: string;
  findings?: Finding[];
  steps: { name: string; ok: boolean; output?: string }[];
}

export function writePlannedMigration(
  projectDir: string,
  baselinePath: string,
  name: string,
  planPath: string,
  now = Date.now()
): PlannedMigration {
  const before: ApsorcType = JSON.parse(
    fs.readFileSync(baselinePath).toString()
  );
  const after: ApsorcType = JSON.parse(
    fs.readFileSync(path.join(projectDir, ".apsorc")).toString()
  );
  const previous: Plan | undefined = fs.existsSync(planPath)
    ? JSON.parse(fs.readFileSync(planPath).toString())
    : undefined;
  const plan = planMigration(before, after, previous);
  fs.mkdirSync(path.dirname(planPath), { recursive: true });
  fs.writeFileSync(planPath, JSON.stringify(plan, null, 2) + "\n");

  const open = openQuestions(plan);
  if (open.length > 0)
    return {
      ok: false,
      needed: true,
      open,
      steps: [
        {
          name: "plan",
          ok: false,
          output: `${open.length} question(s) in ${path.relative(
            projectDir,
            planPath
          )} are open. Answer them with apso migrate plan --answer, then generate again.`,
        },
      ],
    };

  let up: string[];
  let down: DownDdl;
  try {
    up = changeDdl(before, after, plan).up;
    down = downDdl(before, after, plan);
  } catch (error) {
    const output = error instanceof Error ? error.message : String(error);
    return {
      ok: false,
      needed: true,
      steps: [
        {
          name: "render",
          ok: false,
          output: `${output}\nTo use TypeORM's generator instead, rerun with --typeorm.`,
        },
      ],
    };
  }
  if (up.length === 0)
    return { ok: true, needed: false, steps: [{ name: "render", ok: true }] };

  const className = `${pascalCase(name)}Migration${now}`;
  const dir = path.join(projectDir, after.rootFolder || "src", "migrations");
  fs.mkdirSync(dir, { recursive: true });
  const base = `${now}-${name}-migration`;
  const source = typeormMigration(className, up, down);
  fs.writeFileSync(path.join(dir, `${base}.ts`), source);
  fs.writeFileSync(
    path.join(dir, `${base}.plan.json`),
    JSON.stringify(plan, null, 2) + "\n"
  );
  const rel = (f: string) => path.relative(projectDir, path.join(dir, f));
  return {
    ok: true,
    needed: true,
    file: rel(`${base}.ts`),
    planFile: rel(`${base}.plan.json`),
    findings: reviewMigration(source),
    steps: [{ name: "render", ok: true }],
  };
}
