/**
 * Write a migration from an answered plan: up is Apso's change DDL, down the
 * reverse, and the plan is saved beside the migration so the answers that
 * produced it stay with it. The SQL is the same for every language; only the
 * wrapper differs: a TypeORM class, an Alembic revision, or a goose SQL file.
 */
import * as fs from "fs";
import * as path from "path";
import { ApsorcType } from "../apsorc-parser";
import { openQuestions, Plan, planMigration, Question } from "../plan";
import { migrationExtension, migrationsDir } from "../plan/baseline";
import { pascalCase, snakeCase } from "../utils/casing";
import { reviewMigration, Finding } from "../verify/review";
import { changeDdl, DownDdl, downDdl } from "./change";
import { literal } from ".";

const template = (sql: string) =>
  "`" +
  sql.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\${/g, "\\${") +
  "`";
const queries = (statements: string[]) =>
  statements
    .map((s) => `        await queryRunner.query(${template(s)});`)
    .join("\n");

export function typeormMigration(
  className: string,
  up: string[],
  down: DownDdl
): string {
  const downBody =
    "down" in down
      ? queries(down.down)
      : `        throw new Error(${JSON.stringify(irreversible(down))});`;
  return `import { MigrationInterface, QueryRunner } from "typeorm";

// Generated by apso migrate generate from the answered migration plan saved beside this file.
export class ${className} implements MigrationInterface {
    name = '${className}'

    public async up(queryRunner: QueryRunner): Promise<void> {
${queries(up)}
    }

    public async down(queryRunner: QueryRunner): Promise<void> {
${downBody}
    }

}
`;
}

const irreversible = (down: { irreversible: string[] }) =>
  `This migration can't be reversed automatically: ${down.irreversible.join(
    "; "
  )}`;

/**
 * A Python string literal for any SQL. A JSON string is one (same escapes),
 * where """...""" breaks on SQL that ends in a quoted identifier (#148).
 */
export const pyString = (s: string): string => JSON.stringify(s);

const executes = (statements: string[]) =>
  statements.map((s) => `    op.execute(${pyString(s)})`).join("\n");

export function alembicMigration(
  revision: string,
  downRevision: string | undefined,
  up: string[],
  down: DownDdl
): string {
  const downBody =
    "down" in down
      ? executes(down.down) || "    pass"
      : `    raise NotImplementedError(${pyString(irreversible(down))})`;
  return `"""Generated by apso migrate generate from the answered migration plan saved beside this file."""
from alembic import op

revision = ${pyString(revision)}
down_revision = ${downRevision === undefined ? "None" : pyString(downRevision)}
branch_labels = None
depends_on = None


def upgrade() -> None:
${executes(up)}


def downgrade() -> None:
${downBody}
`;
}

/**
 * Statements for a goose SQL file. goose splits on lines ending in ";", so a
 * statement with a ";" of its own is fenced with StatementBegin/End.
 */
export const gooseStatements = (statements: string[]): string =>
  statements
    .map((s) =>
      s.includes(";")
        ? `-- +goose StatementBegin\n${s};\n-- +goose StatementEnd`
        : `${s};`
    )
    .join("\n");

export function gooseMigration(up: string[], down: DownDdl): string {
  // goose has no way to refuse a down, so the SQL refuses it instead.
  const downBody =
    "down" in down
      ? gooseStatements(down.down)
      : gooseStatements([
          `DO $$ BEGIN RAISE EXCEPTION ${literal(
            irreversible(down).replace(/%/g, "%%")
          )}; END $$`,
        ]);
  return `-- Generated by apso migrate generate from the answered migration plan saved beside this file.
-- +goose Up
${gooseStatements(up)}

-- +goose Down
${downBody}
`;
}

/** The newest Alembic revision: the one no other revision names as its down_revision. */
export function alembicHead(dir: string): string | undefined {
  if (!fs.existsSync(dir)) return undefined;
  const revisions: string[] = [];
  const downs = new Set<string>();
  for (const f of fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".py"))
    .sort()) {
    const source = fs.readFileSync(path.join(dir, f)).toString();
    const rev = source.match(/^revision\b[^\n=]*=\s*["']([^"']+)["']/m);
    if (rev) revisions.push(rev[1]);
    const down = source.match(/^down_revision\b[^\n=]*=(.*)$/m);
    for (const d of down?.[1].matchAll(/["']([^"']+)["']/g) ?? [])
      downs.add(d[1]);
  }
  return revisions.filter((r) => !downs.has(r)).pop();
}

const calls = (body: string) =>
  [...body.matchAll(/^\s*op\.execute\((".*")\)\s*$/gm)]
    .map((m) => JSON.parse(m[1]) as string)
    .join(";\n");

/**
 * The up and down SQL of an Alembic or goose migration, for running it on a
 * database without the framework. down is undefined when it refuses to run.
 */
export function migrationSql(
  file: string,
  source: string
): { up: string; down?: string } {
  if (file.endsWith(".sql")) {
    const [up, down = ""] = source
      .split(/^-- \+goose Down\b.*$/m)
      .map((s) => s.replace(/^[\S\s]*?^-- \+goose Up\b.*$/m, ""));
    return { up, down: /RAISE EXCEPTION/.test(down) ? undefined : down };
  }
  const [upBody, downBody = ""] = source.split(/^def downgrade\b/m);
  return {
    up: calls(upBody),
    down: /raise NotImplementedError/.test(downBody) ? undefined : calls(downBody),
  };
}

export interface PlannedMigration {
  ok: boolean;
  needed: boolean;
  /** Questions still open in the plan; nothing is written while any are. */
  open?: Question[];
  file?: string;
  planFile?: string;
  findings?: Finding[];
  steps: { name: string; ok: boolean; output?: string }[];
}

export function writePlannedMigration(
  projectDir: string,
  before: ApsorcType,
  name: string,
  planPath: string,
  now = Date.now()
): PlannedMigration {
  const after: ApsorcType = JSON.parse(
    fs.readFileSync(path.join(projectDir, ".apsorc")).toString()
  );
  const previous: Plan | undefined = fs.existsSync(planPath)
    ? JSON.parse(fs.readFileSync(planPath).toString())
    : undefined;
  const plan = planMigration(before, after, previous);
  fs.mkdirSync(path.dirname(planPath), { recursive: true });
  fs.writeFileSync(
    planPath,
    JSON.stringify({ ...plan, before }, null, 2) + "\n"
  );

  const open = openQuestions(plan);
  if (open.length > 0)
    return {
      ok: false,
      needed: true,
      open,
      steps: [
        {
          name: "plan",
          ok: false,
          output: `${open.length} question(s) in ${path.relative(
            projectDir,
            planPath
          )} are open. Answer them with apso migrate plan --answer, then generate again.`,
        },
      ],
    };

  let up: string[];
  let down: DownDdl;
  try {
    up = changeDdl(before, after, plan).up;
    down = downDdl(before, after, plan);
  } catch (error) {
    const output = error instanceof Error ? error.message : String(error);
    return {
      ok: false,
      needed: true,
      steps: [
        {
          name: "render",
          ok: false,
          output: `${output}\nTo use TypeORM's generator instead, rerun with --typeorm.`,
        },
      ],
    };
  }
  if (up.length === 0)
    return { ok: true, needed: false, steps: [{ name: "render", ok: true }] };

  const className = `${pascalCase(name)}Migration${now}`;
  const dir = migrationsDir(projectDir, after);
  fs.mkdirSync(dir, { recursive: true });
  // goose orders by the number before "_", and its own files use
  // YYYYMMDDHHMMSS, so Python and Go use that too.
  const stamp = new Date(now).toISOString().replace(/\D/g, "").slice(0, 14);
  const base =
    after.language === "python" || after.language === "go"
      ? `${stamp}_${snakeCase(name)}`
      : `${now}-${name}-migration`;
  const file = base + migrationExtension(after);
  const source =
    after.language === "python"
      ? alembicMigration(stamp, alembicHead(dir), up, down)
      : after.language === "go"
      ? gooseMigration(up, down)
      : typeormMigration(className, up, down);
  fs.writeFileSync(path.join(dir, file), source);
  fs.writeFileSync(
    path.join(dir, `${base}.plan.json`),
    // The schemas let later runs find the baseline without being told.
    JSON.stringify({ ...plan, before, after }, null, 2) + "\n"
  );
  // The answers now live beside the migration; the next change starts fresh.
  fs.rmSync(planPath, { force: true });
  const rel = (f: string) => path.relative(projectDir, path.join(dir, f));
  return {
    ok: true,
    needed: true,
    file: rel(file),
    planFile: rel(`${base}.plan.json`),
    // The review reads TypeORM's wrapper; the SQL is the same in all three.
    findings: reviewMigration(typeormMigration(className, up, down)),
    steps: [{ name: "render", ok: true }],
  };
}
